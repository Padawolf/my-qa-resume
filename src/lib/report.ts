/**
 * Formato do resumo publicado em `last-run.json` pelo CI
 * (gerado por `scripts/summarize-report.mjs` a partir do relatório JSON do Cucumber).
 */
export type Lang = 'pt' | 'en';
export type Status = 'passed' | 'failed' | 'skipped';

export interface StepCounts {
  passed: number;
  failed: number;
  skipped: number;
}

export interface ScenarioRun {
  name: string;
  status: Status;
  durationMs: number;
  steps: StepCounts;
  error?: string;
}

export interface FeatureRun {
  name: string;
  uri?: string;
  scenarios: ScenarioRun[];
}

export interface RunReport {
  generatedAt: string;
  commit?: string;
  runUrl?: string;
  durationMs: number;
  features: FeatureRun[];
}

export type OutKind = 'cmd' | 'info' | 'feat' | 'ok' | 'fail' | 'skip' | 'err' | 'sum' | 'build-ok' | 'build-fail' | 'blank';

export interface OutLine {
  kind: OutKind;
  text: string;
}

const isObj = (x: unknown): x is Record<string, unknown> => typeof x === 'object' && x !== null;

/** Valida o JSON baixado antes de usar: um arquivo quebrado não pode derrubar o site. */
export function isRunReport(x: unknown): x is RunReport {
  if (!isObj(x) || typeof x.generatedAt !== 'string' || typeof x.durationMs !== 'number' || !Array.isArray(x.features)) return false;
  return x.features.every(
    (f) =>
      isObj(f) &&
      typeof f.name === 'string' &&
      Array.isArray(f.scenarios) &&
      f.scenarios.every(
        (s) =>
          isObj(s) &&
          typeof s.name === 'string' &&
          (s.status === 'passed' || s.status === 'failed' || s.status === 'skipped') &&
          typeof s.durationMs === 'number' &&
          isObj(s.steps),
      ),
  );
}

export interface Totals {
  scenarios: StepCounts & { total: number };
  steps: StepCounts & { total: number };
}

export function totals(report: RunReport): Totals {
  const sc = { passed: 0, failed: 0, skipped: 0, total: 0 };
  const st = { passed: 0, failed: 0, skipped: 0, total: 0 };
  for (const f of report.features) {
    for (const s of f.scenarios) {
      sc[s.status]++;
      sc.total++;
      st.passed += s.steps.passed;
      st.failed += s.steps.failed;
      st.skipped += s.steps.skipped;
    }
  }
  st.total = st.passed + st.failed + st.skipped;
  return { scenarios: sc, steps: st };
}

/** Idioma da feature pela pasta: tests/e2e/features/pt/... ou tests/e2e/features/en/... */
const LANG_DIR = /\/features\/(pt|en)\//;

/**
 * O CI roda as features E2E nas duas línguas. A janela Saída mostra só as do idioma da página.
 * Features sem pasta de idioma (relatórios antigos) aparecem nos dois. Se o filtro não deixar
 * nada, mostra o relatório inteiro, para a janela nunca ficar vazia.
 */
export function reportForLang(report: RunReport, lang: Lang): RunReport {
  const features = report.features.filter((f) => {
    const m = f.uri?.replace(/\\/g, '/').match(LANG_DIR);
    return !m || m[1] === lang;
  });
  if (features.length === 0 || features.length === report.features.length) return report;
  const durationMs = features.reduce((sum, f) => sum + f.scenarios.reduce((s, sc) => s + sc.durationMs, 0), 0);
  return { ...report, features, durationMs };
}

/** Mesmo formato do Cucumber: 0m4.213s */
export function formatDuration(ms: number): string {
  const totalSeconds = Math.max(0, ms) / 1000;
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = totalSeconds - minutes * 60;
  return `${minutes}m${seconds.toFixed(3)}s`;
}

/** Linha de resumo no estilo do Cucumber: "4 Scenarios (1 failed, 3 passed)". */
export function countLine(label: 'Scenarios' | 'Steps', c: StepCounts & { total: number }): string {
  const parts: string[] = [];
  if (c.failed) parts.push(`${c.failed} failed`);
  if (c.skipped) parts.push(`${c.skipped} skipped`);
  if (c.passed) parts.push(`${c.passed} passed`);
  return `${c.total} ${label} (${parts.join(', ') || '0 passed'})`;
}

const TEXT = {
  pt: {
    scenario: 'Cenário',
    feature: 'Funcionalidade',
    ci: 'commit',
    success: '[INFO] BUILD SUCCESS · nenhum bug escapou para produção',
    failure: '[INFO] BUILD FAILURE · o pipeline segurou o deploy',
    none: [
      'Nenhum relatório do CI encontrado.',
      'Ele é gerado no GitHub Actions a cada push na main.',
      'Para gerar localmente: npm run test:e2e && npm run report',
    ],
  },
  en: {
    scenario: 'Scenario',
    feature: 'Feature',
    ci: 'commit',
    success: '[INFO] BUILD SUCCESS · no bugs escaped to production',
    failure: '[INFO] BUILD FAILURE · the pipeline blocked the deploy',
    none: [
      'No CI report found.',
      'It is generated by GitHub Actions on every push to main.',
      'To generate it locally: npm run test:e2e && npm run report',
    ],
  },
} as const;

export function formatRun(report: RunReport, lang: Lang): OutLine[] {
  const t = TEXT[lang];
  const out: OutLine[] = [];
  const when = report.generatedAt.replace('T', ' ').slice(0, 16) + ' UTC';
  out.push({ kind: 'cmd', text: '$ npx bddgen && npx playwright test' });
  out.push({ kind: 'info', text: `[CI] ${report.commit ? `${t.ci} ${report.commit} · ` : ''}${when}` });

  for (const f of report.features) {
    out.push({ kind: 'blank', text: '' });
    out.push({ kind: 'feat', text: `${t.feature}: ${f.name}` });
    for (const s of f.scenarios) {
      const icon = s.status === 'passed' ? '✔' : s.status === 'failed' ? '✘' : '↷';
      const kind: OutKind = s.status === 'passed' ? 'ok' : s.status === 'failed' ? 'fail' : 'skip';
      out.push({ kind, text: `  ${icon} ${t.scenario}: ${s.name}  (${(s.durationMs / 1000).toFixed(2)}s)` });
      if (s.error) out.push({ kind: 'err', text: `      → ${s.error}` });
    }
  }

  const tot = totals(report);
  out.push({ kind: 'blank', text: '' });
  out.push({ kind: 'sum', text: countLine('Scenarios', tot.scenarios) });
  out.push({ kind: 'sum', text: countLine('Steps', tot.steps) });
  out.push({ kind: 'info', text: formatDuration(report.durationMs) });
  const failed = tot.scenarios.failed > 0;
  out.push({ kind: failed ? 'build-fail' : 'build-ok', text: failed ? t.failure : t.success });
  return out;
}

export function formatNoReport(lang: Lang): OutLine[] {
  return [
    { kind: 'cmd', text: '$ cat last-run.json' },
    ...TEXT[lang].none.map((text, i) => ({ kind: (i === 0 ? 'sum' : 'info') as OutKind, text })),
  ];
}
